"""Тексты режима и проверка полей анкеты."""
from __future__ import annotations

import re

from . import config

NAME_RE = re.compile(r"^[\w\s\-']+$", re.UNICODE)


def validate_name(raw: str) -> tuple[bool, str]:
    name = " ".join(raw.split())
    if len(name) < config.NAME_MIN_LEN:
        return False, f"Слишком короткое имя — нужно минимум {config.NAME_MIN_LEN} символа."
    if len(name) > config.NAME_MAX_LEN:
        return False, f"Слишком длинное имя — максимум {config.NAME_MAX_LEN} символов."
    if not NAME_RE.match(name):
        return False, "В имени можно использовать только буквы, цифры, пробел, дефис и апостроф."
    if any(x in name.lower() for x in ("http", "t.me", "@", "www.")):
        return False, "Ссылки и юзернеймы в имени размещать нельзя."
    return True, name


def validate_age(raw: str | int) -> tuple[bool, str | int]:
    try:
        age = int(str(raw).strip())
    except (TypeError, ValueError):
        return False, "Возраст нужно указать числом, например 24."
    if age < config.MIN_AGE:
        return False, (
            f"Режим доступен только с {config.MIN_AGE} лет. "
            "Если вам меньше — пользоваться им нельзя."
        )
    if age > config.MAX_AGE:
        return False, "Проверьте возраст — похоже на опечатку."
    return True, age


